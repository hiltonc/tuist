#!/bin/sh
# Stands in for a localized-strings generator: one catalog in, typed accessors out. Paired
# with swiftgen-assets.sh to put two generators on a single target, and the only one here
# whose output depends on a declared environment variable.
#
# Environment for a per-target generator:
#
#   TUIST_INPUTS_FILE        JSON array of {type, path}
#   TUIST_OUTPUT_SOURCES_DIR where to write; Tuist creates it before invoking. A staging
#                            directory, moved into place only after this script exits zero:
#                            write files into it, but do not hard-code its path inside them,
#                            because the files end up somewhere else.
#   TUIST_TARGET_NAME        the owning target
#   TUIST_ROOT_DIR           repo root
#   TUIST_PROJECT_DIR        the project directory, NOT the repo root
#   STRINGS_ACCESS_LEVEL     declared via `environment:`, so it is in the cache key
#
# Declared values are ADDED to the inherited environment, not a replacement for it. PATH has
# to stay reachable for `mise`, SwiftGen and Apollo, and hashing it would break cache hits
# between machines for the same reason absolute checkout paths are excluded. `environment:`
# promotes one variable into the cache key; it does not fence off the rest. The
# `.script("… --version")` input is the mitigation for what PATH still influences, namely
# which build of the tool actually ran.
set -e

VERSION="1.0.0"
if [ "$1" = "--version" ]; then echo "fixture-strings $VERSION"; exit 0; fi

: "${TUIST_INPUTS_FILE:?must be set}"
: "${TUIST_OUTPUT_SOURCES_DIR:?must be set}"
: "${TUIST_TARGET_NAME:?must be set}"

# Unset rather than empty is the distinction that matters: an undeclared variable would
# make output depend on ambient state that never reached the cache key.
: "${STRINGS_ACCESS_LEVEL:?must be declared via environment:}"
case "$STRINGS_ACCESS_LEVEL" in
    public|internal) ;;
    *) echo "error: STRINGS_ACCESS_LEVEL must be public or internal" >&2; exit 1 ;;
esac

CATALOG=$(/usr/bin/python3 -c '
import json, sys
inputs = json.load(open(sys.argv[1]))
print(next((e["path"] for e in inputs
            if e["type"] == "file" and e["path"].endswith(".json")), ""))
' "$TUIST_INPUTS_FILE")

[ -f "$CATALOG" ] || { echo "error: no .json string catalog among declared inputs" >&2; exit 1; }

# Values are inlined rather than resolved from a bundle at runtime, which keeps the output a
# pure source file: both the key set and the values are functions of the declared input.
/usr/bin/python3 -c '
import json, re, sys
catalog, target, access = json.load(open(sys.argv[1])), sys.argv[3], sys.argv[4]

def identifier(key):
    # Upper-casing only the first character, never .capitalize(), which would lower the
    # rest and turn "account.signOut" into "accountSignout".
    head, *rest = re.split(r"[^0-9A-Za-z]+", key)
    return head + "".join(p[:1].upper() + p[1:] for p in rest)

with open(sys.argv[2], "w") as out:
    out.write("// AUTO-GENERATED by strings.sh. DO NOT EDIT.\n\n")
    out.write("%s enum %sStrings {\n" % (access, target))
    for key in sorted(catalog):
        out.write("    %s static let %s = %s\n"
                  % (access, identifier(key), json.dumps(catalog[key])))
    out.write("}\n")
' "$CATALOG" "$TUIST_OUTPUT_SOURCES_DIR/${TUIST_TARGET_NAME}Strings.swift" \
  "$TUIST_TARGET_NAME" "$STRINGS_ACCESS_LEVEL"
