#!/bin/sh
# Stands in for `swiftgen run xcassets`, doing the job of Tuist's built-in `.assets()`
# resource synthesizer through the public primitive instead. Same inputs (every
# .xcassets under the target's resources), same output filename, same declared API surface
# Verified by diffing real `.assets()` output. See README.md, "Parity with .assets()".
#
# Environment for a per-target generator, which has exactly one output directory:
#
#   TUIST_INPUTS_FILE   JSON array of {type, path}, resolved absolute: one `file` entry per
#                       `.file` and per `.glob` match, one `folder` entry per `.folder`.
#                       `.script` inputs are absent
#   TUIST_OUTPUT_SOURCES_DIR  where to write; Tuist creates it before invoking. A staging
#                       directory, moved into place only after this script exits zero: write
#                       files into it, but do not hard-code its path inside them, because the
#                       files end up somewhere else.
#   TUIST_TARGET_NAME   the owning target
#   TUIST_ROOT_DIR      repo root
#   TUIST_PROJECT_DIR   the project directory, NOT the repo root
#
# The script computes no paths of its own. Everything arrives resolved, which is a
# correctness property rather than tidiness: a second, independent path computation can
# disagree with what the manifest declared and Tuist hashed, and a script reading only
# $TUIST_INPUTS_FILE *cannot* read an undeclared input.
set -e

VERSION="1.0.0"
if [ "$1" = "--version" ]; then echo "fixture-swiftgen-assets $VERSION"; exit 0; fi

: "${TUIST_INPUTS_FILE:?must be set}"
: "${TUIST_OUTPUT_SOURCES_DIR:?must be set}"
: "${TUIST_TARGET_NAME:?must be set}"

# Selecting inputs by their declared `type` is the point of the JSON form over a
# newline-separated variable: the resources root is a `.folder`, the template a `.file`,
# so neither declaration order nor filename conventions matter here.
eval "$(/usr/bin/python3 -c '
import json, shlex, sys
inputs = json.load(open(sys.argv[1]))
def first(kind, suffix=""):
    return next((e["path"] for e in inputs
                 if e["type"] == kind and e["path"].endswith(suffix)), "")
print("RESOURCES_ROOT=" + shlex.quote(first("folder")))
print("TEMPLATE=" + shlex.quote(first("file", ".stencil")))
' "$TUIST_INPUTS_FILE")"

[ -n "$RESOURCES_ROOT" ] || { echo "error: no folder input to scan for catalogs" >&2; exit 1; }
[ -f "$TEMPLATE" ] || { echo "error: no .stencil template among declared inputs" >&2; exit 1; }

OUT="$TUIST_OUTPUT_SOURCES_DIR/TuistAssets+${TUIST_TARGET_NAME}.swift"

CATALOGS=$(find "$RESOURCES_ROOT" -name '*.xcassets' -type d 2>/dev/null | sort)
CATALOG_COUNT=$(printf '%s\n' "$CATALOGS" | grep -c . || true)

# Failing rather than emitting a valid-but-empty enum: "produced nothing" and "failed" are
# different outcomes, and silently writing an empty enum would hide a mis-scoped input.
# Tuist's own policy for a generator that legitimately emits nothing is a warning.
[ "$CATALOG_COUNT" -gt 0 ] || { echo "error: no .xcassets found under $RESOURCES_ROOT" >&2; exit 1; }

# `{Target}Colors`, not a shared `ColorAsset`, so two targets in one module cannot collide.
COLOR_TYPE="${TUIST_TARGET_NAME}Colors"

emit_colorsets() {
    # $1 = catalog dir, $2 = indent
    find "$1" -name '*.colorset' -type d 2>/dev/null | sort | while read -r CS; do
        NAME=$(basename "$CS" .colorset)
        echo "$2public static let $NAME = $COLOR_TYPE(name: \"$NAME\")"
    done
}

{
    echo "// Generated by swiftgen-assets.sh $VERSION using $(basename "$TEMPLATE"). DO NOT EDIT."
    echo
    echo "#if os(macOS)"
    echo "import AppKit"
    echo "#else"
    echo "import UIKit"
    echo "#endif"
    echo
    echo "public enum ${TUIST_TARGET_NAME}Asset: Sendable {"
    if [ "$CATALOG_COUNT" -gt 1 ]; then
        # The built-in nests a namespace per catalog once there is more than one
        # (AssetsTemplate.swift:114-119), confirmed against real generated output.
        printf '%s\n' "$CATALOGS" | while IFS= read -r CATALOG; do
            [ -n "$CATALOG" ] || continue
            echo "  public enum $(basename "$CATALOG" .xcassets) {"
            emit_colorsets "$CATALOG" "    "
            echo "  }"
        done
    else
        emit_colorsets "$CATALOGS" "  "
    fi
    echo "}"
    echo
    echo "public final class $COLOR_TYPE: Sendable {"
    echo "  public let name: String"
    echo "  fileprivate init(name: String) { self.name = name }"
    echo "}"
} > "$OUT"
